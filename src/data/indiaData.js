/**
 * Searches and resolves any Indian city, town, village, notable place, or state instantly.
 * Provides fallback coordinates even without an external geocoder key or network connection.
 * @param {string} query
 * @returns {object|null}
 */
export function findIndiaPlace(query) {
  if (!query || typeof query !== 'string') return null;
  const raw = query.trim().toLowerCase();
  if (!raw) return null;

  // Normalize tokens: "Hampi, Karnataka, India" -> ["hampi", "karnataka", "india"]
  const clean = raw.replace(/\bindia\b/g, '').replace(/,/g, ' ').replace(/\s+/g, ' ').trim();
  const tokens = clean.split(' ').filter(Boolean);

  // 1. Direct or partial match in curated notable places/villages/towns
  for (const [key, place] of Object.entries(INDIA_NOTABLE_COORDINATES)) {
    if (clean === key || clean.startsWith(key) || tokens.includes(key)) {
      return {
        name: place.name,
        label: `${place.name}, ${place.state ? place.state + ', ' : ''}India`,
        lat: place.lat,
        lon: place.lon,
        type: place.type,
        state: place.state,
        rangeM: place.type === 'village' ? 1200 : (place.type === 'town' ? 2000 : 2800),
      };
    }
  }

  // 2. Search all cities in all 28 states and 8 union territories
  for (const region of INDIA_STATES_AND_UTS) {
    for (const city of region.cities) {
      const cName = city.name.toLowerCase();
      if (clean === cName || tokens.includes(cName) || (clean.includes(cName) && cName.length >= 4)) {
        return {
          name: city.name,
          label: `${city.name}, ${region.name}, India`,
          lat: city.lat,
          lon: city.lon,
          type: 'city',
          state: region.name,
          rangeM: 2800,
        };
      }
    }
  }

  // 3. Search state/UT capitals
  for (const region of INDIA_STATES_AND_UTS) {
    const cap = region.capital.toLowerCase();
    if (clean === cap || tokens.includes(cap)) {
      return {
        name: region.capital,
        label: `${region.capital}, ${region.name}, India`,
        lat: region.lat,
        lon: region.lon,
        type: 'city',
        state: region.name,
        rangeM: 2800,
      };
    }
  }

  // 4. Search notable place names in regions
  for (const region of INDIA_STATES_AND_UTS) {
    for (const placeName of region.notablePlaces) {
      const pName = placeName.toLowerCase();
      if (clean === pName || clean.includes(pName) || tokens.some(t => t.length >= 4 && pName.includes(t))) {
        // Use region lat/lon if specific coordinates not in table
        return {
          name: placeName,
          label: `${placeName}, ${region.name}, India`,
          lat: region.lat,
          lon: region.lon,
          type: 'town',
          state: region.name,
          rangeM: 2000,
        };
      }
    }
  }

  // 5. Search state / union territory itself
  const region = findIndiaRegion(clean);
  if (region) {
    return {
      name: region.name,
      label: `${region.name}, India`,
      lat: region.lat,
      lon: region.lon,
      type: region.type,
      state: region.name,
      viewBounds: region.viewBounds,
      rangeM: region.rangeM || 500000,
    };
  }

  return null;
}

