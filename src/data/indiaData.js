/**
 * Find state or union territory by ID or name (case-insensitive fuzzy match).
 * @param {string} query
 * @returns {object|null}
 */
export function findIndiaRegion(query) {
  if (!query) return null;
  const q = String(query).trim().toLowerCase();
  return INDIA_STATES_AND_UTS.find(
    (item) => item.id === q || item.name.toLowerCase() === q || item.name.toLowerCase().includes(q),
  ) || null;
}

/**
 * Filter states or UTs by search keyword.
 * @param {string} filterText
 * @returns {Array<object>}
 */
export function filterIndiaRegions(filterText) {
  if (!filterText) return INDIA_STATES_AND_UTS;
  const term = filterText.trim().toLowerCase();
  return INDIA_STATES_AND_UTS.filter((r) => {
    if (r.name.toLowerCase().includes(term)) return true;
    if (r.capital.toLowerCase().includes(term)) return true;
    if (r.cities.some((c) => c.name.toLowerCase().includes(term))) return true;
    if (r.notablePlaces.some((p) => p.toLowerCase().includes(term))) return true;
    return false;
  });
}

